const TAG_BY_SITUATION = {
  магазин: 'магазин',
  офис: 'офис',
  без_готовки: 'готовое',
  готовка: 'готовить',
  кафе: 'кафе',
  веган: 'веган',
};

const shuffle = (arr) => {
  const copy = [...arr];
  for (let i = copy.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
};

/**
 * Выдача перемешана намеренно: если возвращать список в одном порядке,
 * модель будет называть первые три позиции каждый раз.
 */
function options({ situation, exclude = [], limit = 8 } = {}) {
  const tag = TAG_BY_SITUATION[situation];
  const skip = exclude.map((e) => e.toLowerCase());

  let list = FOODS.filter((f) => !skip.some((e) => f.name.toLowerCase().includes(e)));
  if (tag) list = list.filter((f) => f.tags.includes(tag));
  if (!list.length) list = FOODS;

  return shuffle(list)
    .slice(0, limit)
    .map((f) => ({
      name: f.name,
      per100: { kcal: f.kcal, protein: f.protein, fat: f.fat },
      note: f.note,
      tags: f.tags,
    }));
}

module.exports = { FOODS, options };

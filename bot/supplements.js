/** Вещества, по которым схемы приёма не даём — только риски и врач. */
const RESTRICTED = ['сармс', 'sarms', 'остарин', 'лигандрол', 'рад140', 'rad-140', 'прогормон', 'стероид', 'анабол', 'тестостерон энантат', 'тренболон', 'метан', 'станозолол', 'кленбутерол', 'днф', 'dnp', 'эфедрин', 'гормон роста'];

const norm = (s) => (s || '').toLowerCase().trim();

function find(query) {
  const q = norm(query);
  if (!q) return [];
  return SUPPLEMENTS.filter(
    (s) => norm(s.name).includes(q) || s.alias.some((a) => q.includes(a) || a.includes(q))
  );
}

function isRestricted(query) {
  const q = norm(query);
  return RESTRICTED.some((r) => q.includes(r));
}

/** База под цель: сначала дешёвое и рабочее, экзотика потом. */
function baseStack(goal) {
  const core = ['creatine', 'vitd', 'whey'];
  if (goal === 'cut') core.push('caffeine', 'electrolytes');
  if (goal === 'bulk') core.push('caffeine');
  return SUPPLEMENTS.filter((s) => core.includes(s.id));
}

const byTier = (tier) => SUPPLEMENTS.filter((s) => s.tier === tier);

module.exports = { SUPPLEMENTS, find, isRestricted, baseStack, byTier };
